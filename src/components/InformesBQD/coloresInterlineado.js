export const COLOR_INTERLINEADO_PREDETERMINADO = "LightGray";

export const COLORES_INTERLINEADO = Object.freeze(
    NOMBRES_COLORES_INTERLINEADO.map((nombre) => Object.freeze({
        id:nombre,
        nombre,
        color:nombre
    }))
);

const COLORES_INTERLINEADO_POR_NOMBRE = new Map(
    NOMBRES_COLORES_INTERLINEADO.map((nombre) => [nombre.toLowerCase(), nombre])
);

export function normalizarColorInterlineado(color) {
    if (typeof color !== "string") return COLOR_INTERLINEADO_PREDETERMINADO;
    return COLORES_INTERLINEADO_POR_NOMBRE.get(color.toLowerCase())
        || COLOR_INTERLINEADO_PREDETERMINADO;
}
